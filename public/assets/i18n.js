export function t(lang, key, params = {}) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.zh;
  let str = dict[key] ?? TRANSLATIONS.zh[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
  }
  return str;
}

export function getGreeting(lang, date = new Date()) {
  const h = date.getHours();
  if (h >= 5 && h < 11) return t(lang, "status.greetingMorning");
  if (h >= 11 && h < 14) return t(lang, "status.greetingNoon");
  if (h >= 14 && h < 18) return t(lang, "status.greetingAfternoon");
  if (h >= 18 && h < 23) return t(lang, "status.greetingEvening");
  return t(lang, "status.greetingNight");
}

export function formatRelativeTime(lang, isoStr) {
  if (!isoStr) return t(lang, "status.noManifestTime");
  const ts = new Date(isoStr).getTime();
  if (Number.isNaN(ts)) return "-";
  const diffSec = Math.max(0, Math.floor((Date.now() - ts) / 1000));
  const isEn = lang === "en";
  if (diffSec < 60) return isEn ? "Just now" : "刚刚";
  const diffMin = Math.floor(diffSec / 60);
  if (diffMin < 60) return isEn ? `${diffMin}m ago` : `${diffMin}分钟前`;
  const diffHour = Math.floor(diffMin / 60);
  if (diffHour < 24) return isEn ? `${diffHour}h ago` : `${diffHour}小时前`;
  const diffDay = Math.floor(diffHour / 24);
  return isEn ? `${diffDay}d ago` : `${diffDay}天前`;
}
